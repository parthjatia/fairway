/**
 * Builds streams/pumpfun-filter.js — a self-contained QuickNode Streams filter for Pump.fun / PumpSwap launch trades —
 * by bundling packages/parser/src/pumpfun.ts (+ the shared core helpers) with esbuild. Same code the tests and ingest run.
 * Usage: pnpm --filter @fairway/streams build:filter
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSync } from 'esbuild';

const HERE = dirname(fileURLToPath(import.meta.url));

export function renderPumpFilter(): string {
  const js = buildSync({
    entryPoints: [join(HERE, '..', 'packages', 'parser', 'src', 'pumpfun.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: 'FairwayPump',
    target: 'es2018',
    legalComments: 'none',
    platform: 'neutral',
  }).outputFiles[0]!.text;
  return `/**
 * Fairway — QuickNode Streams filter for token launches (Solana mainnet, dataset: Block).
 * Extracts Pump.fun bonding-curve and PumpSwap trades (create / buy / sell) from each block:
 *   { launchTrades: [{ sig, slot, ts, mint, venue, trader, kind, tokenAmount, solAmount, price }] }
 * or null when the block has none. Used to bootstrap sniper scores (packages/scoring/src/sniper.ts).
 *
 * GENERATED by streams/build-pumpfun-filter.ts from packages/parser/src/pumpfun.ts. Self-contained: no imports, ES2018.
 * Program ids below verified onchain 2026-11-19 (see STREAM_CONFIG.md §Program IDs).
 */
// ==== PROGRAM IDS (mainnet, verified 2026-11-19) ====
var PROGRAMS = { pumpfun: '6EF8rrecthR5Dkzon8Nwu78hRvfCKubJ14M5uBEwF6P', pumpswap: 'pAMMBay6oceH9fJKBRHGP5D4bD4sWpmSwMn52FMfXEA' };
// ==== END PROGRAM IDS ====

${js.trim()}

function main(stream) {
  var data = stream && stream.data !== undefined ? stream.data : stream;
  var trades = FairwayPump.parsePumpPayload(data, PROGRAMS);
  if (!trades.length) return null;
  return { launchTrades: trades };
}
`;
}

if (process.argv[1] && process.argv[1].endsWith('build-pumpfun-filter.ts')) {
  writeFileSync(join(HERE, 'pumpfun-filter.js'), renderPumpFilter());
  console.log('wrote streams/pumpfun-filter.js');
}
