/**
 * Builds streams/launch-filter.js (and the identical streams/pumpfun-filter.js, kept so an existing Stream keeps working) — a self-contained QuickNode Streams filter for Pump.fun / PumpSwap launch trades and
 * fundings of brand-new wallets — by bundling packages/parser/src/launch-stream.ts (pumpfun.ts + funding.ts + the shared
 * core helpers) with esbuild. Same code the tests and ingest run.
 * Usage: pnpm --filter @fairway/streams build:filter
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSync } from 'esbuild';

const HERE = dirname(fileURLToPath(import.meta.url));

export function renderPumpFilter(): string {
  const js = buildSync({
    entryPoints: [join(HERE, '..', 'packages', 'parser', 'src', 'launch-stream.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: 'FairwayPump',
    target: 'es2018',
    legalComments: 'none',
    platform: 'neutral',
  }).outputFiles[0]!.text;
  return `/**
 * Fairway — QuickNode Streams filter for token launches (Solana mainnet, dataset: Block).
 * Extracts, from each block,
 *   - Pump.fun bonding-curve and PumpSwap trades (create / buy / sell) → sniper scores (packages/scoring/src/sniper.ts)
 * (venue "pumpfun" / "pumpswap"), Raydium LaunchLab (LetsBonk, venue "launchlab") and Meteora Dynamic Bonding Curve (Bags, Jupiter
 * Studio, Believe; venue "meteora-dbc"), SOL-quoted launches only
 *   - SOL fundings of brand-new wallets (System Program only, ≥ MIN_FUNDING_SOL) → bundle detection (packages/scoring/src/bundle.ts)
 *   { launchTrades: [{ sig, slot, ts, mint, venue, trader, kind, tokenAmount, solAmount, price }],
 *     fundings: [{ sig, slot, ts, funder, wallet, sol }] }
 * or null when the block has neither.
 *
 * GENERATED by streams/build-pumpfun-filter.ts (written to launch-filter.js and pumpfun-filter.js) from packages/parser/src/launch-stream.ts. Self-contained: no imports, ES2018.
 * Program ids below verified onchain 2026-11-19 (see STREAM_CONFIG.md §Program IDs).
 */
// ==== PROGRAM IDS (mainnet, verified 2026-11-19; LaunchLab and Meteora DBC verified on real blocks 2026-11-20, their ids and vault authorities are in LAUNCHPADS below) ====
var PROGRAMS = { pumpfun: '6EF8rrecthR5Dkzon8Nwu78hRvfCKubJ14M5uBEwF6P', pumpswap: 'pAMMBay6oceH9fJKBRHGP5D4bD4sWpmSwMn52FMfXEA' };
// SOL below this per new wallet is ignored (rent top-ups, dust). Raise it to cut delivery volume.
var MIN_FUNDING_SOL = 0.05;
// ==== END PROGRAM IDS ====

${js.trim()}

function main(stream) {
  var data = stream && stream.data !== undefined ? stream.data : stream;
  return FairwayPump.parseLaunchStream(data, PROGRAMS, MIN_FUNDING_SOL);
}
`;
}

if (process.argv[1] && process.argv[1].endsWith('build-pumpfun-filter.ts')) {
  const src = renderPumpFilter();
  writeFileSync(join(HERE, 'launch-filter.js'), src);
  writeFileSync(join(HERE, 'pumpfun-filter.js'), src);
  console.log('wrote streams/launch-filter.js and streams/pumpfun-filter.js (identical)');
}
