/**
 * Builds streams/filter.js — a single self-contained QuickNode Streams filter — by stripping the
 * types from packages/parser/src/core.ts (esbuild) and inlining it with the pool config.
 * Usage: pnpm --filter @fairway/streams build:filter
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformSync } from 'esbuild';

const HERE = dirname(fileURLToPath(import.meta.url));
export const CONFIG_START = '// ==== FAIRWAY POOL CONFIG (edit me) ====';
export const CONFIG_END = '// ==== END CONFIG ====';

export function renderFilter(pools: unknown[]): string {
  const core = readFileSync(join(HERE, '..', 'packages', 'parser', 'src', 'core.ts'), 'utf8');
  const js = transformSync(core, { loader: 'ts', format: 'iife', globalName: 'FairwayParser', target: 'es2018', legalComments: 'none' }).code;
  return `/**
 * Fairway — QuickNode Streams filter (Solana, dataset: Block).
 * Extracts swaps on the configured pools from each block and returns compact records:
 *   { swaps: [{ sig, slot, ts, pool, venue, trader, side, baseAmount, quoteAmount, execPrice, feeBps, tier?, source }] }
 * or null when nothing matched (so the destination is not called).
 *
 * GENERATED by streams/build-filter.ts from packages/parser/src/core.ts — the same code the ingest
 * service runs. Self-contained: no imports, no require, ES2018. Edit only the CONFIG block below.
 */
${CONFIG_START}
var POOLS = ${JSON.stringify(pools, null, 2)};
${CONFIG_END}

${js.trim()}

function main(stream) {
  var data = stream && stream.data !== undefined ? stream.data : stream;
  var swaps = FairwayParser.parsePayload(data, POOLS);
  if (!swaps.length) return null;
  return { swaps: swaps };
}
`;
}

/** Replace the CONFIG block of a filter.js source (used by tests and dashboard edits). */
export function withPools(src: string, pools: unknown[]): string {
  const a = src.indexOf(CONFIG_START);
  const b = src.indexOf(CONFIG_END);
  if (a < 0 || b < 0) throw new Error('CONFIG markers not found');
  return `${src.slice(0, a)}${CONFIG_START}\nvar POOLS = ${JSON.stringify(pools, null, 2)};\n${src.slice(b)}`;
}

/** Load a filter source as a callable `main` without any module system (like the Streams runtime). */
export function loadMain(src: string): (stream: unknown) => { swaps: unknown[] } | null {
  return new Function(`${src}\n;return main;`)() as (stream: unknown) => { swaps: unknown[] } | null;
}

export const configuredPools = () =>
  (JSON.parse(readFileSync(join(HERE, 'pools.config.json'), 'utf8')) as { pools: Array<Record<string, unknown>> }).pools.map(({ label: _l, ...p }) => p);

if (process.argv[1] && process.argv[1].endsWith('build-filter.ts')) {
  writeFileSync(join(HERE, 'filter.js'), renderFilter(configuredPools()));
  console.log('wrote streams/filter.js');
}
